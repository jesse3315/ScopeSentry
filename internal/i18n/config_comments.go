// TranslateConfigComments 는 각 줄의 '#' 뒤 주석이 알려진 중국어 기본 주석과 같을 때만 한국어로 바꿉니다.
// 설정 값과 사용자가 직접 쓴 주석은 바꾸지 않습니다.
func TranslateConfigComments(s string) string {
	if s == "" {
		return s
	}
	lines := strings.Split(s, "\n")
	changed := false
	for i, line := range lines {
		idx := strings.Index(line, "#")
		if idx < 0 {
			continue
		}
		comment := line[idx+1:]
		trimmed := strings.TrimSpace(comment)
		ko, ok := configCommentKo[trimmed]
		if !ok {
			continue
		}
		lead := comment[:len(comment)-len(strings.TrimLeft(comment, " \t"))]
		trail := comment[len(strings.TrimRight(comment, " \t\r")):]
		lines[i] = line[:idx+1] + lead + ko + trail
		changed = true
	}
	if !changed {
		return s
	}
	return strings.Join(lines, "\n")
}
